"""Generate a small monochrome Chinese font subset for the two secondary pages."""
from pathlib import Path
import argparse
from PIL import Image,ImageDraw,ImageFont

root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--font',default=str(root.parent/'assets/fonts/NotoSansSC.ttf'));args=parser.parse_args()
sources=[root/'src/ui'/name for name in ('data_lab_theme.h','diagnostics_theme.h','zh_text.h','ui_ili9488.h')]
codes=set(range(32,127))
for source in sources:codes.update(ord(ch) for ch in source.read_text(encoding='utf-8') if ord(ch)>126)
codes=sorted(codes);assert all(c<65536 for c in codes)
lines=['// Generated by tools/generate_zh_font.py. Fixed cells, monochrome, flash only.','#pragma once','#include <stdint.h>','namespace obd {',f'constexpr uint16_t kZhGlyphCount={len(codes)};','static const uint16_t kZhCodes[] PROGMEM = {'+','.join(str(c) for c in codes)+'};']
total=0
for size in (12,14,18):
    font=ImageFont.truetype(args.font,size);font.set_variation_by_axes([500]);height=size+2;stride=(size+7)//8;data=[]
    for code in codes:
        glyph=Image.new('L',(size,height));box=font.getbbox(chr(code));ImageDraw.Draw(glyph).text((-box[0],1-box[1]),chr(code),font=font,fill=255)
        assert code==32 or glyph.getbbox() is not None,hex(code)
        for y in range(height):
            for byte in range(stride):
                value=0
                for bit in range(8):
                    x=byte*8+bit
                    if x<size and glyph.getpixel((x,y))>=100:value|=0x80>>bit
                data.append(value)
    lines.append(f'static const uint8_t kZhBits{size}[] PROGMEM = {{')
    for i in range(0,len(data),32):lines.append(' '+','.join(str(n) for n in data[i:i+32])+',')
    lines.append('};');total+=len(data)
lines+=['struct ZhFont {const uint8_t* bits;uint8_t cell,height,stride;};','static const ZhFont kZhFonts[] = {{kZhBits12,12,14,2},{kZhBits14,14,16,2},{kZhBits18,18,20,3}};','}']
(root/'src/ui/zh_font_generated.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'Generated {len(codes)} glyphs, {total} bitmap bytes in flash')
